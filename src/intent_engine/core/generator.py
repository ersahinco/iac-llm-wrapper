"""Generate intent artifacts from validated intent.

Produces decision reports, contract handoff artifacts, lineage, runbooks, and
module input files that engineers use alongside their IaC modules.

The generator uses a registry pattern so new output modules can be added
without modifying core generation logic. Each registered generator is a
function(intent, output_dir) that writes its own files.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from dataclasses import dataclass
from io import StringIO
from pathlib import Path
from typing import Any

import ruamel.yaml

# ---------------------------------------------------------------------------
# Registry
# ---------------------------------------------------------------------------

GeneratorFn = Callable[[Any, Path], None]


@dataclass
class RegisteredGenerator:
    name: str
    fn: GeneratorFn
    priority: int  # lower = earlier
    category: str  # e.g., "core", "security", "workload"
    applies_to: set[str] | None = None


class GeneratorRegistry:
    """Registry of output generators."""

    def __init__(self) -> None:
        self._generators: list[RegisteredGenerator] = []

    def register(
        self,
        name: str,
        fn: GeneratorFn,
        priority: int = 50,
        category: str = "general",
        applies_to: list[str] | set[str] | None = None,
    ) -> None:
        scope = set(applies_to) if applies_to else None
        self._generators.append(RegisteredGenerator(name, fn, priority, category, scope))
        self._generators.sort(key=lambda g: g.priority)

    def generate(self, intent: Any, output_dir: Path, pattern: str | None = None) -> None:
        for gen in self._generators:
            if pattern is not None and gen.applies_to is not None and pattern not in gen.applies_to:
                continue
            gen.fn(intent, output_dir)

    def list(self) -> list[str]:
        return [g.name for g in self._generators]


# Global registry instance
GLOBAL_REGISTRY = GeneratorRegistry()


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _yaml_dump(data: Any) -> str:
    yaml = ruamel.yaml.YAML()
    yaml.default_flow_style = False
    yaml.indent(mapping=2, sequence=4, offset=2)
    buf = StringIO()
    yaml.dump(data, buf)
    return "\n".join(line.rstrip() for line in buf.getvalue().splitlines()) + "\n"


def _write(output_dir: Path, name: str, data: Any, schema_version: str | None = None) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    if schema_version and isinstance(data, dict):
        data = {"schemaVersion": schema_version, **data}
    header = (
        "# yaml-language-server: $schema=none\n"
        "# Generated by intent-engine — intent artifact, "
        "not deployable configuration.\n"
    )
    (output_dir / name).write_text(header + _yaml_dump(data))


def register_generator(
    name: str,
    fn: GeneratorFn,
    priority: int = 50,
    category: str = "custom",
    applies_to: list[str] | set[str] | None = None,
) -> None:
    """Register a custom generator without modifying core code."""
    GLOBAL_REGISTRY.register(name, fn, priority, category, applies_to)


def generate_all(intent: Any, output_dir: Path, pattern: str | None = None) -> None:
    from .module_mapping import DesignDocument, IaCIntentPayload

    if isinstance(intent, IaCIntentPayload):
        payload = intent
    else:
        payload = IaCIntentPayload(
            design_doc=DesignDocument(),
            module_inputs=[],
            intent=intent,
        )
    GLOBAL_REGISTRY.generate(payload, output_dir, pattern=pattern)


def gen_design_doc(intent: Any, output_dir: Path) -> None:
    """Write design-doc.yaml when business context is present."""
    if not hasattr(intent, "design_doc"):
        return
    dd = intent.design_doc
    if not any(
        [
            dd.project_name,
            dd.business_justification,
            dd.estimated_tier,
            dd.compliance_tags,
        ]
    ):
        return
    data = {
        "projectName": dd.project_name,
        "businessJustification": dd.business_justification,
        "estimatedTier": dd.estimated_tier,
        "complianceTags": dd.compliance_tags,
    }
    _write(output_dir, "design-doc.yaml", data)


def gen_module_inputs(intent: Any, output_dir: Path) -> None:
    """Write module-inputs.yaml when module mappings exist."""
    if not hasattr(intent, "module_inputs"):
        return
    inputs = intent.module_inputs
    if not inputs:
        return
    data = {
        "moduleInputs": [{"moduleName": mi.module_name, "variables": mi.variables} for mi in inputs]
    }
    _write(output_dir, "module-inputs.yaml", data)


def _hcl_value(value: Any) -> str:
    """Format a Python value as an HCL literal for .tfvars."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int | float):
        return str(value)
    if isinstance(value, list):
        items = ", ".join(_hcl_value(v) for v in value)
        return f"[{items}]"
    if isinstance(value, dict):
        # Flatten nested dicts as dotted keys in the caller; this fallback
        # writes a simple HCL object literal — rarely needed for tfvars.
        pairs = ", ".join(f"{k} = {_hcl_value(v)}" for k, v in value.items())
        return "{" + pairs + "}"
    # Strings (and anything else) get quoted
    return json.dumps(str(value))


def gen_tfvars(intent: Any, output_dir: Path) -> None:
    """Write terraform.tfvars from module_inputs when mappings exist."""
    if not hasattr(intent, "module_inputs"):
        return
    inputs = intent.module_inputs
    if not inputs:
        return

    lines: list[str] = []
    lines.append("# Generated by intent-engine — Terraform variables from module inputs.")
    lines.append("")

    for mi in inputs:
        lines.append(f"# Module: {mi.module_name}")
        for key, value in mi.variables.items():
            lines.append(f"{key} = {_hcl_value(value)}")
        lines.append("")

    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "terraform.tfvars").write_text("\n".join(lines))


def gen_sample_recommendations(intent: Any, output_dir: Path) -> None:
    """Write sample-recommendations.yaml when pattern-backed samples exist."""
    if not hasattr(intent, "pattern") or not hasattr(intent, "decisions"):
        return

    pattern = getattr(intent, "pattern", "")
    decisions = getattr(intent, "decisions", {})
    if not pattern or not decisions:
        return

    from .sample_config import GLOBAL_SAMPLE_REGISTRY, SampleConfig

    matches = GLOBAL_SAMPLE_REGISTRY.find_best_matches(decisions, pattern=pattern, limit=3)
    if not matches:
        return

    data = {
        "pattern": pattern,
        "currentDecisions": SampleConfig.to_builtin(decisions),
        "recommendations": [
            {
                "name": match.sample.name,
                "description": match.sample.description,
                "version": match.sample.version,
                "releaseDate": match.sample.release_date,
                "sourceUrl": match.sample.source_url,
                "sourceContract": match.sample.source_contract,
                "upstreamVariant": match.sample.upstream_variant,
                "tags": match.sample.tags,
                "sameDecisionCount": match.same_count,
                "differentDecisionCount": match.different_count,
                "missingDecisionCount": match.missing_count,
                "totalSampleDecisions": match.total_sample_decisions,
                "sameDecisions": sorted(match.diff["same"].keys()),
                "differentDecisions": SampleConfig.to_builtin(match.diff["different"]),
                "missingDecisions": SampleConfig.to_builtin(match.diff["missing_in_current"]),
                "extraCurrentDecisions": SampleConfig.to_builtin(match.diff["extra_in_current"]),
            }
            for match in matches
        ],
    }
    _write(output_dir, "sample-recommendations.yaml", data)


def gen_llm_trace_summary(intent: Any, output_dir: Path) -> None:
    """Write a lean summary of extraction evidence when compile captured it."""
    summary = getattr(intent, "extraction_summary", None)
    if not summary:
        return
    _write(output_dir, "llm-trace-summary.yaml", summary)


def gen_model_benchmark(intent: Any, output_dir: Path) -> None:
    """Write model behavior rollups from the extraction trace."""
    summary = getattr(intent, "extraction_summary", None)
    if not summary:
        return
    from .observability import build_model_benchmark

    _write(output_dir, "model-benchmark.yaml", build_model_benchmark(summary))


def _artifact_owner(artifact_name: str) -> str:
    lowered = artifact_name.lower()
    if "security" in lowered or "iam" in lowered:
        return "security-owner"
    if "network" in lowered or "vpc" in lowered or "cluster" in lowered:
        return "network-owner"
    if "account" in lowered or "organization" in lowered or "global" in lowered:
        return "platform-owner"
    return "target-owner"


def gen_handoff_plan(intent: Any, output_dir: Path) -> None:
    """Write a generic handoff plan from pattern contracts and readiness."""
    pattern = getattr(intent, "pattern", "")
    if not pattern:
        return

    from .patterns import GLOBAL_REGISTRY as PATTERN_REGISTRY

    pattern_obj = PATTERN_REGISTRY.get(pattern)
    readiness = getattr(intent, "deployment_readiness", {}) or {}
    allowed = bool(readiness.get("deploymentAllowed", True))
    contracts = pattern_obj.contracts
    required_artifacts = list(
        dict.fromkeys(
            artifact for contract in contracts for artifact in contract.required_artifacts
        )
    )

    review_steps = [
        {
            "id": f"review-{artifact_name.replace('.', '-').replace('_', '-')}",
            "title": f"Review {artifact_name}",
            "owner": _artifact_owner(artifact_name),
            "dependsOn": ["validate-target-contracts"],
            "manualGate": True,
            "rollback": "Reject the handoff, correct the source intent, and re-run compile.",
        }
        for artifact_name in required_artifacts
    ]
    review_step_ids = [step["id"] for step in review_steps]
    data = {
        "pattern": pattern,
        "boundary": (
            "iac-llm-wrapper emits validated handoff artifacts only; downstream "
            "generation, execution, dashboards, and cloud changes remain outside this artifact."
        ),
        "allowedNextAction": (
            "Resolve blockers and re-run compile before any downstream handoff."
            if not allowed
            else "Pass the reviewed artifacts to the existing target toolchain after manual gates."
        ),
        "readiness": {
            "status": readiness.get("status", "ready" if allowed else "blocked"),
            "deploymentAllowed": allowed,
            "blockers": readiness.get("blockers", []),
        },
        "targetContracts": [
            {
                "name": contract.name,
                "kind": contract.kind,
                "sourceUrl": contract.source_url,
                "requiredArtifacts": contract.required_artifacts,
            }
            for contract in contracts
        ],
        "steps": [
            {
                "id": "resolve-decisions",
                "title": "Confirm captured decisions and blockers",
                "owner": "architecture-owner",
                "dependsOn": [],
                "manualGate": True,
                "rollback": "Update the design document or interview answers and re-run compile.",
            },
            {
                "id": "validate-target-contracts",
                "title": "Validate required artifacts against target contracts",
                "owner": "platform-owner",
                "dependsOn": ["resolve-decisions"],
                "manualGate": True,
                "rollback": "Stop handoff until contract validation is clean.",
            },
            *review_steps,
            {
                "id": "approve-handoff",
                "title": "Approve handoff to existing provisioning toolchain",
                "owner": "release-owner",
                "dependsOn": review_step_ids or ["validate-target-contracts"],
                "manualGate": True,
                "rollback": "Keep the previous approved artifact bundle as the active handoff.",
            },
        ],
        "manualGates": [
            "No blocking gaps or contradictions remain.",
            "Target contract validation is clean.",
            "Artifact owners approve files in their domain.",
            "Rollback owner and previous known-good handoff are identified.",
        ],
        "rollback": [
            "Do not mutate downstream systems from this plan.",
            "Revert to the previous approved handoff bundle in the target toolchain.",
            "Regenerate artifacts only from corrected intent.",
        ],
    }
    _write(output_dir, "handoff-plan.yaml", data)


register_generator("design-doc", gen_design_doc, priority=4, category="meta")
register_generator("module-inputs", gen_module_inputs, priority=5, category="meta")
register_generator("llm-trace-summary", gen_llm_trace_summary, priority=5, category="meta")
register_generator("model-benchmark", gen_model_benchmark, priority=5, category="meta")
register_generator("handoff-plan", gen_handoff_plan, priority=6, category="meta")
register_generator(
    "sample-recommendations",
    gen_sample_recommendations,
    priority=5,
    category="meta",
)
register_generator("terraform-tfvars", gen_tfvars, priority=5, category="meta")
